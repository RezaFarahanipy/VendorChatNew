package com.example.vendorchat.chat

/** لحن گفتگو: رسمی، دوستانه، خودمونی (قابل تنظیم در تنظیمات). */
object Tone {
    const val FORMAL = 0
    const val FRIENDLY = 1
    const val CASUAL = 2
    val names = listOf("رسمی", "دوستانه", "خودمونی")

    fun clamp(t: Int) = t.coerceIn(0, 2)

    fun instruction(t: Int): String = when (clamp(t)) {
        FORMAL -> "لحن: رسمی و مؤدبانه؛ مخاطب را «شما» خطاب کن و از زبان معیار استفاده کن."
        FRIENDLY -> "لحن: گرم، دوستانه و محترمانه؛ ساده و روان صحبت کن و گاهی یک ایموجی مناسب بگذار."
        else -> "لحن: کاملاً خودمونی و محاوره‌ای، مثل یک دوست صمیمی و بامزه (تو، می‌خوای، چطوری، باشه، حله، ...). کوتاه و پرانرژی؛ گاهی ایموجی بگذار."
    }

    fun sample(t: Int): String = when (clamp(t)) {
        FORMAL -> "سلام. چه کمکی از دست من برمی‌آید؟"
        FRIENDLY -> "سلام! چه کمکی می‌تونم بکنم؟ 😊"
        else -> "به به سلام! چی کار داری باهام؟ 😄"
    }

    private fun pick(t: Int, a: String, b: String, c: String) = when (clamp(t)) {
        FORMAL -> a
        FRIENDLY -> b
        else -> c
    }

    fun cancelled(t: Int) = pick(t, "لغو شد.", "باشه، لغو شد.", "باشه، بیخیالش شدیم 👍")
    fun done(t: Int) = pick(t, "انجام شد.", "انجام شد ✅", "تمام! انجام شد 😎")
    fun noModel(t: Int) = pick(
        t,
        "برای گفتگوی هوشمند، مدل زبانی باید فعال باشد. از دکمهٔ تنظیمات مدل را اضافه کنید.",
        "برای گفتگوی هوشمند باید مدل زبانی فعال باشه. از تنظیمات (آیکن چرخ‌دنده) اضافه‌ش کن.",
        "بدون مدل نمی‌تونم حرف بزنم 😅 از تنظیمات (چرخ‌دنده) مدل رو اضافه کن تا خوب باهم گپ بزنیم."
    )
    fun loading(t: Int) = pick(
        t,
        "مدل در حال بارگذاری است؛ چند لحظه دیگر دوباره بپرسید.",
        "مدل داره بارگذاری می‌شه؛ چند لحظه دیگه دوباره بپرس.",
        "یه چند ثانیه صبر کن، دارم گرم می‌شم 🔥"
    )
    fun noMatch(t: Int) = pick(
        t,
        "وندوری مرتبط با درخواست شما پیدا نشد.",
        "وندوری با این مشخصات پیدا نکردم.",
        "چیزی پیدا نکردم 🤷 شاید اسمش یه کم فرق داره؟"
    )
    fun emptyDb(t: Int) = pick(
        t,
        "هنوز وندوری ثبت نشده است. می‌توانید بگویید: «وندور فولاد اصفهان را اضافه کن، تلفن ...».",
        "هنوز وندوری ثبت نشده. مثلاً بگو: «وندور فولاد اصفهان رو اضافه کن، تلفن ...».",
        "هنوز هیچ وندوری ندارم! بگو «وندور فولاد اصفهان رو اضافه کن، تلفنش ...» تا شروع کنیم 🚀"
    )
    fun undone(t: Int) = pick(t, "تغییر آخر برگردانده شد.", "تغییر آخر برگشت ↩️", "برگردوندم ↩️ انگار نه انگار 😉")
    fun nothingToUndo(t: Int) = pick(t, "تغییری برای برگرداندن نیست.", "چیزی برای برگردوندن نیست.", "چیزی برای برگردوندن ندارم 🙂")
    fun askVendor(t: Int) = pick(t, "منظور شما کدام وندور است؟", "منظورت کدوم وندوره؟", "کدوم وندور رو می‌گی؟ 🤔")
}
